def main():
    apply = "--apply" in sys.argv
    log = []
    for rel, company, project, node in MOVES:
        src = os.path.join(PEND, rel)
        dst_dir = os.path.join(ROOT, "1_项目结算", company, project, node)
        dst = os.path.join(dst_dir, os.path.basename(src))
        if not os.path.exists(src):
            print("  缺失:", rel); continue
        if os.path.exists(dst):
            print("  目标已存在，跳过:", rel); continue
        print(f"  [{company}/{project}/{node}] {os.path.basename(src)}")
        if apply:
            os.makedirs(dst_dir, exist_ok=True)
            shutil.move(src, dst)
        log.append({"公司": company, "项目": project, "节点": node,
                    "新路径": os.path.relpath(dst, ROOT), "原位置": rel})
    rel, up = UPSTREAM
    src = os.path.join(PEND, rel)
    if os.path.exists(src):
        dst_dir = os.path.join(ROOT, up)
        dst = os.path.join(dst_dir, os.path.basename(src))
        print(f"  [上游] {os.path.basename(src)}")
        if apply:
            os.makedirs(dst_dir, exist_ok=True)
            if not os.path.exists(dst):
                shutil.move(src, dst)
        log.append({"公司": "上游合同", "项目": "试油公司", "节点": "01_合同协议",
                    "新路径": os.path.relpath(dst, ROOT), "原位置": rel})

    if apply:
        # 自底向上清空目录
        for dp, dirnames, fns in os.walk(PEND, topdown=False):
            if not dirnames and not fns:
                os.rmdir(dp)
        with open(os.path.join(OUT, "待确认拆分日志.csv"), "w", newline="", encoding="utf-8-sig") as f:
            w = csv.DictWriter(f, fieldnames=["公司", "项目", "节点", "新路径", "原位置"])
            w.writeheader(); w.writerows(log)
        print(f"\n[split_pending] 拆分 {len(log)} 个文件 -> output/待确认拆分日志.csv")
    else:
        print(f"\n干跑 {len(log)} 个，加 --apply 执行。")

if __name__ == "__main__":
    main()
